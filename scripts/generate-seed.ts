// Writes supabase/seed.sql from design/data/*.json with the BUILD_PLAN corrections applied.
// Run: npm run db:seed:generate
import { writeFileSync } from "node:fs";
import { designDestinations, designRankings, designScholarships, designUniversities } from "../src/lib/content/design-data";
import { disciplines } from "../src/lib/taxonomy";
import { enumArray, jsonb, lit, textArray } from "./sql";

const destinations = designDestinations();
const universities = designUniversities();
const scholarships = designScholarships();
const rankings = designRankings();

const out: string[] = [
  "-- Generated by scripts/generate-seed.ts from design/data/*.json. Do not edit by hand.",
  "-- Ranks: THE World University Rankings 2027 as recorded in the brief (design/data/universities.json).",
  "-- Seeding never overwrites a rank already edited in the admin (on conflict do nothing).",
  "begin;",
  "",
];

out.push("insert into public.destinations (code, name, why, sort_order) values");
out.push(
  destinations.map((d) => `  (${lit(d.code)}, ${lit(d.name)}, ${lit(d.why)}, ${d.sortOrder})`).join(",\n") +
    "\non conflict (code) do update set name = excluded.name, why = excluded.why, sort_order = excluded.sort_order;",
  "",
);

out.push("insert into public.disciplines (slug, name, includes, sort_order) values");
out.push(
  disciplines.map((d, i) => `  (${lit(d.slug)}, ${lit(d.name)}, ${lit(d.includes)}, ${i + 1})`).join(",\n") +
    "\non conflict (slug) do update set name = excluded.name, includes = excluded.includes, sort_order = excluded.sort_order;",
  "",
);

out.push("insert into public.universities (id, name, city, country_code, levels) values");
out.push(
  universities
    .map((u) => `  (${lit(u.id)}, ${lit(u.name)}, ${lit(u.city)}, ${lit(u.countryCode)}, ${enumArray(u.levels, "level_code")})`)
    .join(",\n") +
    "\non conflict (id) do update set name = excluded.name, city = excluded.city, country_code = excluded.country_code, levels = excluded.levels;",
  "",
);

out.push(
  "insert into public.rankings (university_id, country_code, rank_display, rank_sort, year, source, source_url, updated_by) values",
);
out.push(
  rankings
    .map(
      (r) =>
        `  (${lit(r.universityId)}, ${lit(r.countryCode)}, ${lit(r.rankDisplay)}, ${r.rankSort}, ${r.year}, ${lit(r.source)}, ${lit(r.sourceUrl)}, 'seed')`,
    )
    .join(",\n") + "\non conflict (university_id, year) do nothing;",
  "",
);

const cols = [
  "id", "name", "funder", "funder_type", "award_type", "destination_code", "university_id", "levels",
  "disciplines_all", "disciplines", "discipline_label", "opens", "closes", "deadline_note", "awards", "summary",
  "official_url", "last_verified", "verification_status", "human_check_note", "eligibility", "documents",
  "timeline", "where_usable",
];
out.push(`insert into public.scholarships (${cols.join(", ")}) values`);
out.push(
  scholarships
    .map((s) =>
      "  (" +
      [
        lit(s.id), lit(s.name), lit(s.funder), lit(s.funderType), lit(s.awardType), lit(s.destinationCode),
        lit(s.universityId), enumArray(s.levels, "level_code"), lit(s.disciplinesAll), textArray(s.disciplines),
        lit(s.disciplineLabel), lit(s.opens), lit(s.closes), lit(s.deadlineNote), lit(s.awards), lit(s.summary),
        lit(s.officialUrl), lit(s.lastVerified), lit(s.verificationStatus), lit(s.humanCheckNote),
        textArray(s.eligibility), textArray(s.documents), jsonb(s.timeline), lit(s.whereUsable),
      ].join(", ") +
      ")",
    )
    .join(",\n") +
    "\non conflict (id) do update set " +
    cols.filter((c) => c !== "id").map((c) => `${c} = excluded.${c}`).join(", ") +
    ";",
  "",
);

// A university's own scholarship is usable there.
const owned = scholarships.filter((s) => s.universityId);
out.push("insert into public.scholarship_universities (scholarship_id, university_id) values");
out.push(owned.map((s) => `  (${lit(s.id)}, ${lit(s.universityId)})`).join(",\n") + "\non conflict do nothing;", "");

out.push("insert into public.verification_log (scholarship_id, verified_at, status, note)");
out.push(
  "select v.id, v.verified::timestamptz, v.status::public.verification_status, 'Imported from the design handoff'",
  "from (values",
  scholarships.map((s) => `  (${lit(s.id)}, ${lit(s.lastVerified)}, ${lit(s.verificationStatus)})`).join(",\n"),
  ") as v (id, verified, status)",
  "where not exists (select 1 from public.verification_log l where l.scholarship_id = v.id);",
  "",
  "commit;",
  "",
);

writeFileSync(new URL("../supabase/seed.sql", import.meta.url), out.join("\n"));
console.log(
  `seed.sql: ${destinations.length} destinations, ${disciplines.length} disciplines, ${universities.length} universities, ${rankings.length} ranks, ${scholarships.length} scholarships`,
);
