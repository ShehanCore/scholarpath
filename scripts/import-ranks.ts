// Turns a rankings CSV into SQL that adds or updates rows in public.rankings (option 2 in the build plan:
// a file you downloaded yourself). It never fetches anything.
//
//   npm run db:ranks -- path/to/ranks.csv [--year 2027] [--out file.sql]
//
// CSV columns (header row required): rank,name[,university_id]. Copy rank and name exactly as published
// ("=17", "301–350"). Use university_id to force a match. Only universities ScholarPath lists are imported;
// unmatched rows are reported. Writes supabase/ranks/ranks-<year>.sql unless --out is given.
// Check the publisher's terms before publishing more ranks than your scholarships need.
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { designUniversities } from "../src/lib/content/design-data";
import { RANK_SOURCE_URL, RANK_YEAR } from "../src/lib/rank";
import { lit } from "./sql";
import { matchRanks, parseCsv } from "./rank-csv";

const args = process.argv.slice(2);
const option = (name: string) => (args.includes(name) ? args[args.indexOf(name) + 1] : undefined);
const file = args.find((a, i) => !a.startsWith("--") && !args[i - 1]?.startsWith("--"));
const year = Number(option("--year") ?? RANK_YEAR);
if (!file || !Number.isInteger(year)) {
  console.error("Usage: npm run db:ranks -- <file.csv> [--year 2027] [--out file.sql]");
  process.exit(1);
}
const source = `Times Higher Education World University Rankings ${year}`;

const [header, ...body] = parseCsv(readFileSync(file, "utf8"));
const col = (name: string) => header.findIndex((h) => h.trim().toLowerCase() === name);
const [rankCol, nameCol, idCol] = [col("rank"), col("name"), col("university_id")];
if (rankCol < 0 || nameCol < 0) {
  console.error('The CSV needs a header row with "rank" and "name" columns.');
  process.exit(1);
}
const rows = body.map((r) => ({ rank: r[rankCol] ?? "", name: r[nameCol] ?? "", universityId: idCol >= 0 ? r[idCol] : undefined }));
const universities = designUniversities();
const country = new Map(universities.map((u) => [u.id, u.countryCode]));
const { matches, badRank } = matchRanks(rows, universities);
const matchedNames = new Set(matches.map((m) => m.theName));

const sql = [
  `-- Generated by scripts/import-ranks.ts from ${file}.`,
  "begin;",
  ...matches.map(
    (m) =>
      "insert into public.rankings (university_id, country_code, rank_display, rank_sort, year, source, source_url, updated_by) " +
      `values (${lit(m.universityId)}, ${lit(country.get(m.universityId) ?? "")}, ${lit(m.rank)}, ${m.rank.match(/\d+/)?.[0]}, ` +
      `${year}, ${lit(source)}, ${lit(RANK_SOURCE_URL)}, 'csv import') ` +
      "on conflict (university_id, year) do update set rank_display = excluded.rank_display, rank_sort = excluded.rank_sort, " +
      "source = excluded.source, source_url = excluded.source_url, updated_by = excluded.updated_by;",
  ),
  "commit;",
  "",
];
const target = option("--out") ?? fileURLToPath(new URL(`../supabase/ranks/ranks-${year}.sql`, import.meta.url));
mkdirSync(dirname(target), { recursive: true });
writeFileSync(target, sql.join("\n"));

console.log(`Matched ${matches.length} universities → ${target}`);
if (badRank.length) console.log(`Skipped (not a rank): ${badRank.map((r) => `${r.name} "${r.rank}"`).join("; ")}`);
const skipped = rows.filter((r) => !matchedNames.has(r.name) && !badRank.includes(r));
if (skipped.length) console.log(`Not a ScholarPath university, skipped: ${skipped.length} rows`);
