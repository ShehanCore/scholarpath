// Turns a CSV copied from THE World University Rankings 2027 into SQL that sets universities.the_rank.
//
//   npm run db:ranks -- path/to/the-wur-2027.csv --retrieved 2026-10-26 [--out file.sql]
//
// CSV columns (header row required): rank,name[,university_id]. Copy rank and name exactly as THE shows them
// at https://www.timeshighereducation.com/world-university-rankings. Use university_id to force a match.
// Writes supabase/ranks/the-wur-2027.sql unless --out is given. Every university not in the CSV is reset to "Rank band: to confirm".
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { designUniversities } from "../src/lib/content/design-data";
import { RANK_SOURCE_URL } from "../src/lib/rank";
import { lit } from "./sql";
import { matchRanks, parseCsv } from "./the-ranks";

const args = process.argv.slice(2);
const file = args.find((a, i) => !a.startsWith("--") && !args[i - 1]?.startsWith("--"));
const option = (name: string) => (args.includes(name) ? args[args.indexOf(name) + 1] : undefined);
const retrieved = option("--retrieved");
const outFile = option("--out");
if (!file || !retrieved || !/^\d{4}-\d{2}-\d{2}$/.test(retrieved)) {
  console.error("Usage: npm run db:ranks -- <file.csv> --retrieved YYYY-MM-DD");
  process.exit(1);
}

const [header, ...body] = parseCsv(readFileSync(file, "utf8"));
const col = (name: string) => header.findIndex((h) => h.trim().toLowerCase() === name);
const [rankCol, nameCol, idCol] = [col("rank"), col("name"), col("university_id")];
if (rankCol < 0 || nameCol < 0) {
  console.error('The CSV needs a header row with "rank" and "name" columns.');
  process.exit(1);
}
const rows = body.map((r) => ({ rank: r[rankCol] ?? "", name: r[nameCol] ?? "", universityId: idCol >= 0 ? r[idCol] : undefined }));

const { matches, unmatched, badRank } = matchRanks(rows, designUniversities());

const sql = [
  `-- Generated by scripts/import-the-ranks.ts from ${file}, retrieved ${retrieved}.`,
  "-- Source: Times Higher Education World University Rankings 2027.",
  "begin;",
  "update public.universities set the_rank = null, rank_source_url = null, rank_retrieved_at = null;",
  ...matches.map(
    (m) =>
      `update public.universities set the_rank = ${lit(m.rank)}, rank_source_url = ${lit(RANK_SOURCE_URL)}, ` +
      `rank_retrieved_at = ${lit(retrieved)} where id = ${lit(m.universityId)}; -- ${m.theName.replace(/\n/g, " ")}`,
  ),
  "commit;",
  "",
];
const target = outFile ?? fileURLToPath(new URL("../supabase/ranks/the-wur-2027.sql", import.meta.url));
mkdirSync(dirname(target), { recursive: true });
writeFileSync(target, sql.join("\n"));

console.log(`Matched ${matches.length} universities → ${target}`);
if (badRank.length) console.log(`Skipped (rank not in THE format): ${badRank.map((r) => `${r.name} "${r.rank}"`).join("; ")}`);
if (unmatched.length) console.log(`Not in the CSV, will show "Rank band: to confirm": ${unmatched.map((u) => u.name).join(", ")}`);
